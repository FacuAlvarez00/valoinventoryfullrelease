// Resolve a battle pass image by display name
export const getBattlePassImage = (displayName) => {
  if (!displayName) {
    console.log('🎮 [getBattlePassImage] displayName es null/undefined');
    return null;
  }

  console.log('🎮 [getBattlePassImage] Looking up image for:', displayName);
  const imageName = battlePassImages[displayName];

  if (imageName) {
    const fullPath = `/assets/battlepasses/${imageName}`;
    console.log('🎮 [getBattlePassImage] Image found:', fullPath);
    return fullPath;
  }

  console.log('🎮 [getBattlePassImage] No image found for:', displayName);
  console.log('🎮 [getBattlePassImage] Claves disponibles:', Object.keys(battlePassImages).slice(0, 10));
  return null;
};

