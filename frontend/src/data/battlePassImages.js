// Función para obtener la imagen de un battle pass por nombre
export const getBattlePassImage = (displayName) => {
  if (!displayName) {
    console.log('🎮 [getBattlePassImage] displayName es null/undefined');
    return null;
  }
  
  console.log('🎮 [getBattlePassImage] Buscando imagen para:', displayName);
  const imageName = battlePassImages[displayName];
  
  if (imageName) {
    const fullPath = `/assets/battlepasses/${imageName}`;
    console.log('🎮 [getBattlePassImage] Imagen encontrada:', fullPath);
    return fullPath;
  }
  
  console.log('🎮 [getBattlePassImage] No se encontró imagen para:', displayName);
  console.log('🎮 [getBattlePassImage] Claves disponibles:', Object.keys(battlePassImages).slice(0, 10));
  return null; // Retorna null si no hay imagen
};

